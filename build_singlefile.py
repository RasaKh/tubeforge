    ap = argparse.ArgumentParser(description="TubeForge")
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=5000)
    ap.add_argument("--downloads")
    ap.add_argument("--debug", action="store_true")
